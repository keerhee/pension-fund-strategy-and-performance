def pic(s, name, x, y, w, h):
    """상자 (x,y,w,h) 안에 비율을 지켜 가운데 놓는다."""
    from PIL import Image
    p = os.path.join(ART, name); iw, ih = Image.open(p).size
    sc = min(w / iw, h / ih); ww, hh = iw * sc, ih * sc
    s.shapes.add_picture(p, E(x + (w - ww) / 2), E(y + (h - hh) / 2), E(ww), E(hh))

