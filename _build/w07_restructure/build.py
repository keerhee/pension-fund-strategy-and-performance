def divider(num, label, title, sub):
    s = dup_slide(prs, 5)          # 옛 s06 (1교시 간지) — 글자는 위치로 찾는다
    for sh in s.shapes:
        if not sh.has_text_frame or not sh.text_frame.text.strip(): continue
        x, y, w, h = px(sh)
        if y < 400 and h > 100: set_text(sh, num)
        elif 400 <= y < 460: set_text(sh, label)
        elif 460 <= y < 560: set_text(sh, title)
        elif 560 <= y < 670: set_text(sh, sub)
    return s

