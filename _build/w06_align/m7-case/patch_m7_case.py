def rep(slide, old, new):
    n = 0
    for sh in slide.shapes:
        for tf in lecfix._tf_iter(sh):
            for p in tf.paragraphs:
                hit = False
                for r in p.runs:
                    if old in r.text:
                        r.text = r.text.replace(old, new); n += 1; hit = True
                if not hit and p.runs and old in p.text:
                    p.runs[0].text = p.text.replace(old, new); n += 1
                    for r in p.runs[1:]:
                        r._r.getparent().remove(r._r)
    return n


P = Presentation(SRC)
for no, old, new in FIX:
    n = rep(P.slides[no - 1], old, new)
    if n == 0:
        sys.exit(f"[{no}] 찾지 못함: {old}")
    print(f"s{no:02d} ×{n}  {old[:40]}")

