def split(part):
    p = Presentation(TMP)
    slides = list(p.slides)
    keep = slides[:n1] if part == 1 else slides[n1:]
    kid = set(map(id, keep))
    for s in keep:
        for sh in list(s.shapes):
            ca = sh.click_action
            if ca.target_slide is not None and id(ca.target_slide) not in kid:
                for h in sh._element.xpath(".//a:hlinkClick"):
                    rid = h.get("{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id")
                    if rid: s.part.drop_rel(rid)
                sh._element.getparent().remove(sh._element)
    for i in range(len(slides) - 1, -1, -1):
        if id(slides[i]) not in kid:
            delete_slide(p, i)
    renumber(p)
    idx = {id(s): i for i, s in enumerate(p.slides, 1)}
    for s in p.slides:
        for sh in s.shapes:
            ca = sh.click_action
            if ca.target_slide is not None and sh.has_text_frame and "쪽" in sh.text_frame.text:
                n = idx[id(ca.target_slide)]
                for para in sh.text_frame.paragraphs:
                    for r in para.runs:
                        r.text = re.sub(r"\d+쪽", f"{n}쪽", r.text)
    p.save(OUT[part]); print("저장:", os.path.basename(OUT[part]), len(p.slides), "장")


