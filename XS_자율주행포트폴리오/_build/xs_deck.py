FOOT, TOP, GAP = 6.95, 1.90, 0.22

def _cbox(s, x, y, w, head, code, tone, fs):
    """실습 전용 코드상자 — 여백을 줄인 판이다."""
    n = len(code.split("\n")); h = 0.62 + n * (CODE_LEAD / 72.0)
    _rect(s, x, y, w, 0.34, tone)
    _tb(s, x + 0.20, y + 0.04, w - 0.32, 0.28, head, 13, WHITE, True)
    _rect(s, x, y + 0.34, w, h - 0.34, CODE_BG)
    _tb(s, x + 0.24, y + 0.46, w - 0.48, h - 0.60, code, fs, INK, font=MONO,
        line=Pt(CODE_LEAD), space_after=0)
    return y + h

def _cbox_h(code):
    return 0.62 + len(code.split("\n")) * (CODE_LEAD / 72.0)

STEP_TOP = 1.52

def step(s, where, note, cmd, out, check, cmd_fs=16, out_fs=16):
    """[어디] [입력] [출력] [확인] 네 칸 — 실습 슬라이드의 고정 형식."""
    _rect(s, 0.6, STEP_TOP, 1.15, 0.34, MUTED)
    _tb(s, 0.6, STEP_TOP + 0.03, 1.15, 0.30, "어디", 13, WHITE, True, align=PP_ALIGN.CENTER)
    _tb(s, 1.90, STEP_TOP - 0.01, 4.6, 0.36, where, 16, INK, font=MONO)
    if note:
        _tb(s, 6.7, STEP_TOP + 0.01, 6.0, 0.34, note, 16, MUTED, align=PP_ALIGN.RIGHT)
    y = STEP_TOP + 0.50
    nchk = len([t for t in check.split("\n") if t.strip()])
    need = 0.34 + nchk * 0.31 + 0.04
    total = y + _cbox_h(cmd) + 0.16 + _cbox_h(out) + 0.18 + need
    if total > FOOT + 0.01:
        OVER.append((P[0], round(total - FOOT, 2)))
    y = _cbox(s, 0.6, y, 12.1, "입력", cmd, BLUE, cmd_fs)
    y = _cbox(s, 0.6, y + 0.16, 12.1, "출력", out, NAVY, out_fs) + 0.18
    _rect(s, 0.6, y, 1.15, 0.34, GREEN)
    _tb(s, 0.6, y + 0.03, 1.15, 0.30, "확인", 13, WHITE, True, align=PP_ALIGN.CENTER)
    _tb(s, 1.90, y - 0.02, 10.8, need - 0.04, check, 17, INK, line=1.32)
    return y


